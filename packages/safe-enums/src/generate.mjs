/**
 * Generate safe enum wrappers from a schema.
 *
 * Note: For editing this module, https://ts-ast-viewer.com/ is very handy.
 */
// Note: TypeScript must be imported as a default import, because named-export detection on that
// package is unreliable under Node's ESM loader.
import ts from 'typescript';

import {createSource, getLeadingComments} from './generator-utils.mjs';

const factory = ts.factory;

// Often-used keywords
const u53Keyword = factory.createTypeReferenceNode(factory.createIdentifier('u53'), undefined);
const stringKeyword = factory.createKeywordTypeNode(ts.SyntaxKind.StringKeyword);

/**
 * Comment marking the generated module as generated.
 */
const GENERATED_WARNING_COMMENT =
    '// WARNING: This file has been generated by safe-enums. Do not modify it!';

/**
 * Vim modeline, appended to the generated module.
 */
const VIM_MODELINE = '// vim: set readonly :';

/**
 * Prefix of a TypeScript directive comment, e.g. `// @ts-nocheck`.
 */
const TYPESCRIPT_DIRECTIVE_PREFIX = '// @ts-';

/**
 * Extract lines at the top of a schema containing TypeScript directives, e.g. `// @ts-nocheck`.
 *
 * Note: In the returned `schemaWithoutDirectives`, the line(s) containing directives are blanked
 * instead of removing them entirely, so that the line numbers of the returned schema still match
 * the input schema.
 *
 * @param {string} schema The source text of the schema.
 * @returns {[directives: string[], schemaWithoutDirectives: string]} the topmost lines containing
 *   TypeScript directives, as well as the cleaned schema.
 */
function extractTsDirectives(schema) {
    const lines = schema.split('\n');
    const directives = [];
    for (const line of lines) {
        if (!line.startsWith(TYPESCRIPT_DIRECTIVE_PREFIX)) {
            break;
        }
        directives.push(line);
    }
    const rest = lines.map((line, index) => (index < directives.length ? '' : line)).join('\n');
    return [directives, rest];
}

