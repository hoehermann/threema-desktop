/**
 * An error in the schema, reported with the location of the offending statement.
 */
export class SchemaError extends Error {
    /**
     * Create an error reporting the position of `node` within the schema.
     *
     * @param {string} message The reason why the schema was rejected.
     * @param {ts.SourceFile} source The schema source file.
     * @param {ts.Node} node The offending node.
     */
    constructor(message, source, node) {
        const {line, character} = source.getLineAndCharacterOfPosition(node.getStart(source));
        super(`${source.fileName}:${line + 1}:${character + 1}: ${message}`);
        this.name = 'SchemaError';
    }
}

